const assert=require('assert');
const {createTransportReminders}=require('../app/static/transport-reminders.js');
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)},events=[];
const make=()=>createTransportReminders(storage,jobs=>events.push(jobs.map(j=>j.id)));
let reminders=make();const state={session:{me:'room-a'},paused:false,clock:0,jobs:[{id:'a',kind:'transport',status:'new',vehicles:[],due:3600}]};
reminders.check(state);assert.equal(events.length,0);
state.clock=1799;reminders.check(state);assert.equal(events.length,0);
state.clock=1800;reminders.check(state);assert.deepEqual(events,[['a']]);
state.clock=1801;reminders.check(state);assert.equal(events.length,1);
reminders=make();reminders.check(state);assert.equal(events.length,1,'Reconnect must not repeat a reminder');
state.jobs[0].due=5400;reminders.check(state);assert.equal(events.length,1);
state.clock=3700;state.paused=true;reminders.check(state);assert.equal(events.length,1);
state.paused=false;reminders.check(state);assert.equal(events.length,2,'Changed pickup time gets a new reminder');
state.jobs.push({id:'b',kind:'transport',status:'assigned',vehicles:['unit'],due:3600},{id:'c',kind:'transport',status:'done',vehicles:[],due:3600},{id:'d',kind:'emergency',status:'new',vehicles:[],due:3600});
reminders.check(state);assert.equal(events.length,2,'Assigned, completed and emergency jobs must not gong');
state.jobs.push({id:'e',kind:'transport',status:'new',vehicles:[],due:3700},{id:'f',kind:'transport',status:'new',vehicles:[],due:3600,reserved:'unit'});
reminders.check(state);assert.deepEqual(events.at(-1),['e','f'],'New urgent or reserved jobs gong once as a batch');
state.session.me='room-b';reminders.check(state);assert.equal(events.length,4,'Rooms track reminders separately');
console.log('Transport reminder threshold, persistence, batching and pause tests passed.');
